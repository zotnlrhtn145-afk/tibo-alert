window.TIBO_KOIFY = function (s) {
  if (!s) return null;
  const t = String(s).trim();
  const day = t.match(/^Day\s*(\d+)\s*\/?\s*/i);
  const pre = day ? `Day ${day[1]} · ` : '';
  const body = day ? t.slice(day[0].length) : t;
  const rules = [
    [/^reset\.?$/i, '리셋.'],
    [/usage limits? (have|has) been reset/i, '코덱스 사용량 한도가 리셋되었습니다. 한도를 확인하세요.'],
    [/^banked\s*(\d+)\s*\/\s*(\d+)/i, (m) => `리셋권(뱅크) ${m[1]}/${m[2]} 지급.`],
    [/global reset (landing|by) .*?(EOD|end of day)/i, '태평양 시간 오늘 안에 전체 리셋이 적용됩니다.'],
    [/global reset landing tomorrow\s*(\d+\s*(am|pm))/i, (m) => `내일 태평양 시간 ${m[1]}에 전체 리셋 예정.`],
    [/all propagated|it is all propagated|propagated/i, '리셋이 모든 계정에 적용됐습니다.'],
    [/^(done|it is done|done and dusted)\.?$/i, '리셋 완료.'],
    [/banked reset/i, '리셋권(뱅크 리셋) 지급 안내.'],
    [/(\d+)M (active )?users/i, (m) => `활성 사용자 ${m[1]}00만 명 기념 리셋.`],
    [/reset.*(within|in) the (next )?(hour|\d+\s*min)/i, '리셋이 곧(1시간 안에) 적용됩니다.'],
    [/more resets coming/i, '리셋이 더 있을 예정입니다.'],
    [/reset (usage )?limits? for all/i, '모든 사용자의 사용량 한도를 리셋했습니다.'],
  ];
  for (const [re, out] of rules) { const m = body.match(re); if (m) return pre + (typeof out === 'function' ? out(m) : out); }
  return day ? pre + body : null;
};
